// readme-generator.js
// Generates README.md and SPEC.md for each app pushed to GitHub.

/**
 * Derive a human-readable title from appSlug.
 * "todo-app" → "Todo App"
 */
function titleFromSlug(slug) {
  if (!slug) return 'App';
  return slug
    .replace(/-/g, ' ')
    .replace(/\b\w/g, c => c.toUpperCase());
}

/**
 * Format ISO date to readable string: "6 May 2026"
 */
function formatDate(iso) {
  return new Date(iso).toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric'
  });
}

/**
 * Generate README.md content.
 * @param {object} p
 * @param {string} p.appName      - e.g. "df-todo-app-17"
 * @param {string} p.appSlug      - e.g. "todo-app"
 * @param {string} p.orderDescription
 * @param {object|null} p.spec    - architect spec object
 * @param {string} p.createdAt    - ISO timestamp
 * @returns {string}
 */
export function generateReadme({ appName, appSlug, orderDescription, spec, createdAt }) {
  const title = titleFromSlug(appSlug);
  const date = formatDate(createdAt);
  const summary = spec?.summary || orderDescription;
  const features = spec?.features || [];
  const warnings = spec?.warnings || [];

  const lines = [
    `# ${title}`,
    '',
    `> Generated by **Dark Factory** · ${date}`,
    '',
    summary,
    '',
  ];

  if (features.length > 0) {
    lines.push('## Features', '');
    features.forEach(f => lines.push(`- ${f}`));
    lines.push('');
  }

  lines.push(
    '## Running',
    '',
    '```bash',
    'npm install',
    'npm start',
    '```',
    '',
  );

  if (warnings.length > 0) {
    lines.push('## Notes', '');
    warnings.forEach(w => lines.push(`- ⚠️ ${w}`));
    lines.push('');
  }

  lines.push(
    '---',
    '',
    `**Order:** "${orderDescription}"`,
    '',
    'See [SPEC.md](./SPEC.md) for full specification.',
  );

  return lines.join('\n');
}

/**
 * Generate SPEC.md content.
 * @param {object} p
 * @param {string} p.appName
 * @param {string} p.appSlug
 * @param {string} p.orderDescription
 * @param {object|null} p.spec
 * @param {string} p.createdAt
 * @returns {string}
 */
export function generateSpec({ appName, appSlug, orderDescription, spec, createdAt }) {
  const title = titleFromSlug(appSlug);
  const date = formatDate(createdAt);

  if (!spec) {
    return [
      `# Specification — ${title}`,
      '',
      `**Order:** "${orderDescription}"`,
      `**Generated:** ${date}`,
      '',
      '_Specification not available for this order._',
    ].join('\n');
  }

  const lines = [
    `# Specification — ${title}`,
    '',
    `**Order:** "${orderDescription}"`,
    `**Generated:** ${date}`,
    '',
    '## Summary',
    '',
    spec.summary,
    '',
  ];

  if (spec.features?.length > 0) {
    lines.push('## Features', '');
    spec.features.forEach(f => lines.push(`- ${f}`));
    lines.push('');
  }

  if (spec.screens?.length > 0) {
    lines.push('## Screens', '');
    spec.screens.forEach(s => lines.push(`- ${s}`));
    lines.push('');
  }

  if (spec.constraints?.length > 0) {
    lines.push('## Technical Constraints', '');
    spec.constraints.forEach(c => lines.push(`- ${c}`));
    lines.push('');
  }

  if (spec.warnings?.length > 0) {
    lines.push('## Warnings', '');
    spec.warnings.forEach(w => lines.push(`- ${w}`));
    lines.push('');
  }

  lines.push(
    '---',
    '',
    '<details>',
    '<summary>Raw JSON</summary>',
    '',
    '```json',
    JSON.stringify(spec, null, 2),
    '```',
    '',
    '</details>',
  );

  return lines.join('\n');
}
