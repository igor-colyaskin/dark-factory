// scripts/test-github-client.js
// Integration test: creates repo, commits files, verifies, cleans up.
// Run: node scripts/test-github-client.js
// Requires: connected GitHub account (token in state/github-tokens.json)

import 'dotenv/config';
import githubClient from '../server/github-client.js';
import githubTokens from '../server/github-tokens.js';

const TEST_REPO_NAME = 'df-test-' + Date.now();

async function run() {
  console.log('=== GitHub Client Integration Test ===\n');

  // 0. Check connection
  const tokenData = await githubTokens.read();
  if (!tokenData) {
    console.error('✗ FAIL: GitHub not connected. Run OAuth flow first.');
    process.exit(1);
  }
  console.log(`✓ Token found for @${tokenData.username}`);
  const owner = tokenData.username;

  // 1. getUser()
  console.log('\n--- getUser() ---');
  const userResult = await githubClient.getUser();
  if (!userResult.success) {
    console.error(`✗ FAIL: getUser failed: ${userResult.error}`);
    process.exit(1);
  }
  console.log(`✓ Authenticated as @${userResult.user.login} (id: ${userResult.user.id})`);

  // 2. createRepo()
  console.log(`\n--- createRepo("${TEST_REPO_NAME}") ---`);
  const repoResult = await githubClient.createRepo(TEST_REPO_NAME, {
    private: true,
    description: 'Dark Factory integration test (auto-delete)',
  });
  if (!repoResult.success) {
    console.error(`✗ FAIL: createRepo failed: ${repoResult.error}`);
    process.exit(1);
  }
  console.log(`✓ Created: ${repoResult.repo.url}`);
  console.log(`  Private: ${repoResult.repo.private}`);

  // 3. commitFiles()
  console.log('\n--- commitFiles() ---');
  const files = [
    { path: 'package.json', content: JSON.stringify({ name: 'test-app', version: '1.0.0', scripts: { start: 'node app.js' } }, null, 2) },
    { path: 'app.js', content: 'const http = require("http");\nhttp.createServer((req, res) => { res.end("Hello"); }).listen(8080);\n' },
    { path: 'README.md', content: `# ${TEST_REPO_NAME}\n\nGenerated by Dark Factory (test)\n` },
  ];

  const commitResult = await githubClient.commitFiles(owner, TEST_REPO_NAME, files, 'Initial commit from Dark Factory');
  if (!commitResult.success) {
    console.error(`✗ FAIL: commitFiles failed: ${commitResult.error}`);
    // Cleanup anyway
    await githubClient.deleteRepo(owner, TEST_REPO_NAME);
    process.exit(1);
  }
  console.log(`✓ Committed ${files.length} files (sha: ${commitResult.commitSha.slice(0, 7)})`);

  // 4. setTopics()
  console.log('\n--- setTopics() ---');
  const topicsResult = await githubClient.setTopics(owner, TEST_REPO_NAME, ['dark-factory', 'test']);
  if (topicsResult.success) {
    console.log('✓ Topics set: dark-factory, test');
  } else {
    console.log(`⚠ Topics failed (non-critical): ${topicsResult.error}`);
  }

  // 5. Cleanup
  console.log(`\n--- deleteRepo("${TEST_REPO_NAME}") ---`);
  const deleteResult = await githubClient.deleteRepo(owner, TEST_REPO_NAME);
  if (!deleteResult.success) {
    console.error(`✗ FAIL: deleteRepo failed: ${deleteResult.error}`);
    console.error(`  Manual cleanup needed: https://github.com/${owner}/${TEST_REPO_NAME}/settings`);
    process.exit(1);
  }
  console.log('✓ Repository deleted');

  console.log('\n=== ALL CHECKS PASSED ===');
}

run().catch(err => {
  console.error('Unexpected error:', err);
  process.exit(1);
});